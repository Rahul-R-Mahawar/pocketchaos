export const CHAOS_HEADER = 'X-PocketChaos-Applied';
const JSON_CONTENT_TYPE = 'application/json; charset=utf-8';

type EndpointRecord = IChaosEndpoint & { _id: Types.ObjectId };

interface ProxyResult {
  /** "pocketchaos" = generated by PocketChaos itself; "target" = upstream or mock payload. */
  origin: 'pocketchaos' | 'target';
  status: number;
  headers: Record<string, string>;
  body: Buffer | string;
  tags: string[];
}

/** PocketChaos's own errors (unknown key/route, SSRF block, injected failure) use the standard envelope. */
function envelopeError(status: number, code: string, message: string, tags: string[]): ProxyResult {
  return {
    origin: 'pocketchaos',
    status,
    headers: { 'content-type': JSON_CONTENT_TYPE },
    body: JSON.stringify(errorBody(code, message)),
    tags,
  };
}

const UPSTREAM_ERROR_STATUS: Record<UpstreamErrorCode, number> = {
  SSRF_BLOCKED: 403,
  UPSTREAM_DNS_ERROR: 502,
  UPSTREAM_TIMEOUT: 504,
  UPSTREAM_TOO_LARGE: 502,
  UPSTREAM_ERROR: 502,
};

function detectClientPlatform(req: Request): ClientPlatform {
  const declared = req.get('x-pocketchaos-platform')?.trim().toLowerCase();
  if (declared && (CLIENT_PLATFORMS as readonly string[]).includes(declared)) return declared as ClientPlatform;

  const userAgent = req.get('user-agent') ?? '';
  if (/android|okhttp|dalvik/i.test(userAgent)) return 'android';
  if (/iphone|ipad|ios|cfnetwork|darwin/i.test(userAgent)) return 'ios';
  if (/mozilla/i.test(userAgent)) return 'web';
  return 'unknown';
}

function isHttpMethod(method: string): method is HttpMethod {
  return (HTTP_METHODS as readonly string[]).includes(method);
}

function resolveRequestPath(req: Request): string {
  // Express 5 named wildcard: /proxy/:projectKey{/*splat} -> splat = ["users", "profile"] or undefined.
  const splat = (req.params as Record<string, unknown>).splat;
  const segments = Array.isArray(splat) ? splat.map(String) : [];
  return normalizeEndpointPath(segments.join('/'));
}

function isJsonContentType(contentType: string | undefined): boolean {
  return contentType !== undefined && /[/+]json\b/i.test(contentType);
}

async function fetchFromUpstream(endpoint: EndpointRecord, req: Request, tags: string[]): Promise<ProxyResult> {
  const target = new URL(endpoint.targetUrl as string);
  // Pass the caller's query string through. The host is untouched, but the final URL is re-validated anyway.
  const incoming = new URL(req.originalUrl, 'http://pocketchaos.invalid');
  incoming.searchParams.forEach((value, key) => target.searchParams.append(key, value));

  const check = await checkExternalUrl(target.toString());
  if (!check.safe && check.code === 'DNS_LOOKUP_FAILED') {
    return envelopeError(502, 'UPSTREAM_DNS_ERROR', `Upstream ${check.reason}`, [...tags, 'upstream_dns_error']);
  }
  if (!check.safe) {
    return envelopeError(403, 'SSRF_BLOCKED', `Upstream target blocked: ${check.reason}`, [...tags, 'ssrf_blocked']);
  }

  const hasBody = Buffer.isBuffer(req.body) && req.body.length > 0 && req.method !== 'GET';
  try {
    const upstream = await forwardRequest({
      url: check.url,
      method: req.method,
      headers: req.headers,
      body: hasBody ? (req.body as Buffer) : undefined,
    });
    return { origin: 'target', status: upstream.status, headers: upstream.headers, body: upstream.body, tags };
  } catch (err) {
    if (err instanceof UpstreamError) {
      return envelopeError(UPSTREAM_ERROR_STATUS[err.code], err.code, err.message, [...tags, err.code.toLowerCase()]);
    }
    throw err;
  }
}

function mockResponse(endpoint: EndpointRecord, tags: string[]): ProxyResult {
  const mock = endpoint.mockResponseJson === undefined ? {} : endpoint.mockResponseJson;
  return {
    origin: 'target',
    status: 200,
    headers: { 'content-type': JSON_CONTENT_TYPE },
    body: JSON.stringify(mock),
    tags,
  };
}

function applyJsonCorruption(result: ProxyResult): ProxyResult {
  if (!isJsonContentType(result.headers['content-type'])) {
    return { ...result, tags: [...result.tags, 'corrupt_json:skipped_non_json'] };
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(result.body.toString());
  } catch {
    return { ...result, tags: [...result.tags, 'corrupt_json:skipped_invalid_json'] };
  }
  // Re-serialising is recursive in V8: pass absurdly deep bodies through byte-for-byte instead of crashing.
  if (exceedsDepth(parsed, MAX_CORRUPTIBLE_DEPTH)) {
    return { ...result, tags: [...result.tags, 'corrupt_json:skipped_too_deep'] };
  }

  const { value, corruptedPaths } = corruptJson(parsed);
  return {
    ...result,
    headers: { ...result.headers, 'content-type': JSON_CONTENT_TYPE },
    body: JSON.stringify(value),
    tags: [...result.tags, `corrupt_json:${corruptedPaths.length}`],
  };
}

/**
 * Chaos pipeline, in order:
 *  1. delayMs (capped at 10 s)  2. failureRate roll -> injected 500, upstream never called
 *  3. forward to targetUrl, or serve mockResponseJson  4. overrideStatusCode  5. corruptJson
 * All steps are skipped while chaosConfig.enabled is false.
 */
async function runChaosPipeline(endpoint: EndpointRecord, req: Request): Promise<ProxyResult> {
  const chaos = endpoint.chaosConfig;
  const active = chaos?.enabled === true;
  const tags: string[] = [];

  if (active) {
    const delay = clampDelay(chaos.delayMs);
    if (delay > 0) {
      await sleep(delay);
      tags.push(`delay:${delay}ms`);
    }
    if (shouldInjectFailure(chaos.failureRate)) {
      return envelopeError(500, 'CHAOS_INJECTED_FAILURE', 'PocketChaos injected a simulated server failure', [
        ...tags,
        'failure:500',
      ]);
    }
  }

  let result = endpoint.targetUrl ? await fetchFromUpstream(endpoint, req, tags) : mockResponse(endpoint, tags);
  // SSRF blocks and upstream failures are reported as-is, without further chaos on top.
  if (!active || result.origin === 'pocketchaos') return result;

  if (chaos.overrideStatusCode !== null && chaos.overrideStatusCode !== undefined) {
    result = { ...result, status: chaos.overrideStatusCode, tags: [...result.tags, `status:${chaos.overrideStatusCode}`] };
  }
  if (chaos.corruptJson) {
    result = applyJsonCorruption(result);
  }
  return result;
}

/** ALL /proxy/:projectKey/* */
export const handleProxyRequest: RequestHandler = async (req, res) => {
  const startedAt = performance.now();
  const keyCheck = projectKeySchema.safeParse(req.params.projectKey);
  const path = resolveRequestPath(req);
  const method = req.method.toUpperCase();

  const send = (result: ProxyResult) => {
    res.status(result.status).set(result.headers).set(CHAOS_HEADER, result.tags.join(',') || 'none').send(result.body);
  };

  if (!keyCheck.success) {
    send(envelopeError(400, 'INVALID_PROJECT_KEY', 'projectKey must be 6 letters or digits', []));
    return;
  }
  const projectKey = keyCheck.data;

  const endpoint: EndpointRecord | null = isHttpMethod(method)
    ? await ChaosEndpoint.findOne({ projectKey, method, path }).lean<EndpointRecord>()
    : null;
  let result: ProxyResult;
  if (endpoint) {
    result = await runChaosPipeline(endpoint, req);
  } else if (await projectExists(projectKey)) {
    result = envelopeError(404, 'ENDPOINT_NOT_FOUND', `No ${method} ${path} endpoint is registered for this project`, [
      'no_match',
    ]);
  } else {
    // Unknown key: nothing to log against.
    send(envelopeError(404, 'PROJECT_NOT_FOUND', 'No project found for this key', []));
    return;
  }

  await recordRequestLog({
    endpointId: endpoint?._id ?? null,
    projectKey,
    method,
    path,
    statusReturned: result.status,
    latencyMs: Math.round(performance.now() - startedAt),
    chaosApplied: result.tags.join(',') || 'none',
    clientPlatform: detectClientPlatform(req),
  });
  send(result);
};
